import type { Plugin } from "vite";
import fs from "node:fs";
import path from "node:path";

/**
 * Sites 构建辅助：确保产物结构包含 dist/server/index.js
 * 并在构建后写入最小 server entry 供 Sites 加载。
 */
export function sitesPlugin(): Plugin {
  return {
    name: "sites-vite-plugin",
    apply: "build",
    closeBundle() {
      const root = process.cwd();
      const serverDir = path.join(root, "dist", "server");
      fs.mkdirSync(serverDir, { recursive: true });

      const entry = path.join(serverDir, "index.js");
      if (!fs.existsSync(entry)) {
        // 若 vinext 已输出其他入口，做一层 re-export；否则写占位 worker 入口
        const candidates = [
          path.join(root, "dist", "worker", "index.js"),
          path.join(root, "dist", "rsc", "index.js"),
          path.join(root, ".output", "server", "index.mjs"),
        ];
        const found = candidates.find((p) => fs.existsSync(p));
        if (found) {
          const rel = path.relative(serverDir, found).replace(/\\/g, "/");
          fs.writeFileSync(
            entry,
            `export { default } from "${rel.startsWith(".") ? rel : "./" + rel}";\n`,
            "utf8",
          );
        } else {
          fs.writeFileSync(
            entry,
            `// Sites server entry — generated by sites-vite-plugin\nexport { default } from "../../worker/index.ts";\n`,
            "utf8",
          );
        }
      }

      // 确保 hosting 配置存在
      // Keep the source metadata at the repository root and copy it into the
      // deployable artifact expected by Sites.
      const sourceHostingPath = path.join(root, ".openai", "hosting.json");
      if (!fs.existsSync(sourceHostingPath)) {
        throw new Error("Missing .openai/hosting.json");
      }
      const distOpenaiDir = path.join(root, "dist", ".openai");
      fs.mkdirSync(distOpenaiDir, { recursive: true });
      fs.copyFileSync(sourceHostingPath, path.join(distOpenaiDir, "hosting.json"));
    },
  };
}
